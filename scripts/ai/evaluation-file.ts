/**
 * The measured numbers the app shows (src/ai/evaluation.ts) are generated from raw counts, never typed by hand:
 *
 *   bun scripts/ai/train-local.ts --model src/ai/local/news-model.bin --write-eval
 *
 * evaluates the shipped model, the keyword rules (current tagger) and Jev on the gold set, writes the counts to
 * scripts/ai/evaluation-counts.json and renders src/ai/evaluation.ts from them with `renderEvaluation`. A test
 * (evaluation-file.test.ts) re-renders the checked-in counts and requires the checked-in file to match exactly.
 */

/** Right / total. */
export type Ratio = { k: number; n: number };
/** Binary confusion counts. */
export type Confusion = { tp: number; fp: number; fn: number };

export type MethodCounts = {
	/** About Venezuela, random split. Null: the method does not answer it. */
	about: Ratio | null;
	/** Blackout over all gold items (random + enriched). */
	blackoutAll: Confusion;
	/** Blackout over the random split only: the unbiased estimate (the enriched slice was chosen by the rules). */
	blackoutRandom: Confusion;
	/** Topics, micro over item × topic, random split. */
	topics: Confusion;
	/** Event type, random split. Null: the method does not answer it. */
	event: Ratio | null;
	/** State where the gold is a specific state, all gold items. */
	stateSpecific: Ratio;
};

export type EvaluationCounts = {
	date: string;
	goldItems: number;
	randomItems: number;
	/** The command that produced these counts, verbatim. */
	command: string;
	methods: Record<string, MethodCounts>;
};

export const MARKS = {
	about: 0.9,
	blackoutPR: 0.8,
	topicsMicroF1: 0.75,
	event: 0.7,
	stateSpecific: 0.8,
} as const;
export const LOCAL_MODEL = "vigia-local-news-1";

const r3 = (x: number) => Math.round(x * 1_000) / 1_000;
const ratio = (x: Ratio | null) => (x === null ? null : r3(x.k / Math.max(1, x.n)));
const precision = (c: Confusion) => r3(c.tp / Math.max(1, c.tp + c.fp));
const recall = (c: Confusion) => r3(c.tp / Math.max(1, c.tp + c.fn));
const f1 = (c: Confusion) => r3((2 * c.tp) / Math.max(1, 2 * c.tp + c.fp + c.fn));

/** Wilson score interval, 95 %, for k successes in n trials; [0, 0] when n = 0. */
export function wilson(k: number, n: number, z = 1.96): [number, number] {
	if (n === 0) return [0, 0];
	const p = k / n;
	const d = 1 + (z * z) / n;
	const centre = (p + (z * z) / (2 * n)) / d;
	const half = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
	return [r3(Math.max(0, centre - half)), r3(Math.min(1, centre + half))];
}

export function summarise(m: MethodCounts) {
	return {
		about: ratio(m.about),
		blackoutP: precision(m.blackoutAll),
		blackoutR: recall(m.blackoutAll),
		topicsMicroF1: f1(m.topics),
		event: ratio(m.event),
		stateSpecific: ratio(m.stateSpecific),
	};
}

export function renderEvaluation(data: EvaluationCounts): string {
	const results: Record<string, ReturnType<typeof summarise>> = {};
	const random: Record<string, unknown> = {};
	for (const [id, m] of Object.entries(data.methods)) {
		results[id] = summarise(m);
		const b = m.blackoutRandom;
		random[id] = {
			positives: b.tp + b.fn,
			p: precision(b),
			r: recall(b),
			rInterval95: wilson(b.tp, b.tp + b.fn),
			pInterval95: wilson(b.tp, b.tp + b.fp),
		};
	}
	const local = results[LOCAL_MODEL];
	const localPassed =
		!!local &&
		(local.about ?? 0) >= MARKS.about &&
		local.blackoutP >= MARKS.blackoutPR &&
		local.blackoutR >= MARKS.blackoutPR &&
		local.topicsMicroF1 >= MARKS.topicsMicroF1 &&
		(local.event ?? 0) >= MARKS.event &&
		(local.stateSpecific ?? 0) >= MARKS.stateSpecific;
	const passed = local
		? [
				(local.about ?? 0) >= MARKS.about,
				local.blackoutP >= MARKS.blackoutPR && local.blackoutR >= MARKS.blackoutPR,
				local.topicsMicroF1 >= MARKS.topicsMicroF1,
				(local.event ?? 0) >= MARKS.event,
				(local.stateSpecific ?? 0) >= MARKS.stateSpecific,
			].filter(Boolean).length
		: 0;
	const value = {
		date: data.date,
		goldItems: data.goldItems,
		randomItems: data.randomItems,
		marks: MARKS,
		results,
		blackoutRandom: random,
		blackoutNoteEs: `Apagones: precisión y exhaustividad sobre las ${data.goldItems} noticias, de las cuales ${data.goldItems - data.randomItems} se eligieron porque las reglas de palabras clave ya marcaban un tema poco frecuente; por eso favorecen a las reglas y a los modelos que las usan. La estimación sin ese sesgo es la de las ${data.randomItems} al azar, con pocos casos positivos (intervalo de 95 %).`,
		localPassed,
	};
	return `// GENERATED by ${data.command}
// from scripts/ai/evaluation-counts.json (renderer: scripts/ai/evaluation-file.ts). Do not edit by hand.
/**
 * Measured accuracy on the gold set (docs/AI.md), shown in the app next to every AI feature.
 * The local model met ${passed} of 5 pre-registered marks${localPassed ? "" : ": it ships as experimental, not as the default"}.
 */
export const NEWS_EVALUATION = ${JSON.stringify(value, null, "\t")} as const;
`;
}
