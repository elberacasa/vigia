export function noticeText(adapters: readonly Adapter[] = ADAPTERS, root = ROOT): string {
	const out: string[] = [
		"Vigía",
		"Copyright 2026 elberacasa",
		"",
		"Vigía is licensed under the PolyForm Noncommercial License 1.0.0 (see LICENSE). That licence covers Vigía's",
		"own code only. The third-party software, data and fonts listed below keep their own licences.",
		"",
		"This file is generated by `bun scripts/gen-docs.ts`.",
		"",
		"================================================================================",
		"Third-party software bundled in the client and the release binaries",
		"================================================================================",
		"",
	];
	for (const p of runtimePackages(root)) out.push(`${p.name} ${p.version} (${p.license}) ${p.homepage}`);
	out.push(
		"",
		"Development tools (not distributed): see package.json devDependencies.",
		"",
		"================================================================================",
		"Data and assets included in this repository",
		"================================================================================",
		"",
	);
	for (const d of BUNDLED_DATA) out.push(`${d.what}`, `  Source: ${d.source}`, `  Licence: ${d.licence}`, "");
	out.push(
		"================================================================================",
		"Data fetched at run time",
		"================================================================================",
		"",
		"Vigía fetches data from the sources below when it runs. That data belongs to its publishers and is shown",
		"with their attribution. Where a licence is non-commercial (e.g. CC BY-NC-SA) or reserves redistribution, the",
		"same limits apply to anyone who runs or redistributes Vigía. Per-source details: docs/DATA-SOURCES.md.",
		"",
	);
	const licences = new Map<string, { name: string; url: string; attribution: string; sources: string[] }>();
	for (const a of adapters) {
		const entry = licences.get(a.licence.id) ?? {
			name: a.licence.name,
			url: a.licence.url,
			attribution: a.licence.attribution,
			sources: [],
		};
		entry.sources.push(a.id);
		licences.set(a.licence.id, entry);
	}
	for (const l of [...licences.values()].sort((a, b) => a.name.localeCompare(b.name))) {
		const sources = l.sources.length > 8 ? `${l.sources.length} sources` : l.sources.join(", ");
		out.push(`${l.name}`, `  ${l.url}`, `  Attribution: ${l.attribution}`, `  Used by: ${sources}`, "");
	}
	out.push(
		"Recorded test fixtures under src/adapters/*/fixtures are real responses from those sources, included only",
		"where the source's licence allows redistribution, under that same licence.",
	);
	return `${out.join("\n").trimEnd()}\n`;
}

export interface GeneratedFile {
	readonly path: string;
	readonly content: string;
}

export function generated(root = ROOT): GeneratedFile[] {
	const readme = readFileSync(join(root, "README.md"), "utf8");
	return [
		{ path: "docs/DATA-SOURCES.md", content: dataSourcesMarkdown() },
		{ path: "README.md", content: withReadmeBlock(readme, readmeSourcesBlock()) },
		{ path: "NOTICE", content: noticeText(ADAPTERS, root) },
	];
}

if (import.meta.main) {
	const check = process.argv.includes("--check");
	let stale = 0;
	for (const file of generated()) {
		const path = join(ROOT, file.path);
		const current = existsSync(path) ? readFileSync(path, "utf8") : "";
		if (current === file.content) continue;
		stale++;
		if (check) console.error(`${file.path} is out of date: run bun scripts/gen-docs.ts`);
		else {
			writeFileSync(path, file.content);
			console.log(`wrote ${file.path}`);
		}
	}
	if (check && stale > 0) process.exit(1);
	if (!check && stale === 0) console.log("generated files are current");
}
